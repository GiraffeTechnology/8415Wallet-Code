export const POLICY_CATALOGS = Object.freeze(Object.fromEntries(
  POLICY_LOCALES.map(locale => [locale, Object.freeze({ ...catalogs[locale], ...ceremonyCatalogs[locale], ...sourceScopeCatalogs[locale] })])));
export function policyText(key, parameters = {}, locale = 'en') {
  const language = Object.hasOwn(POLICY_CATALOGS, locale) ? locale : 'en';
  const template = POLICY_CATALOGS[language][key];
  if (typeof template !== 'string') throw new Error('TASK_POLICY_MESSAGE_REFUSED');
  return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (_match, name) => {
    if (!Object.hasOwn(parameters, name)) throw new Error('TASK_POLICY_MESSAGE_PARAMETER_REFUSED');
    return String(parameters[name]);
  });
}
